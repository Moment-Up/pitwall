"""Track skeleton (layer L0a): the game's own sector boundaries and zones, in metres along the lap.

The F1 Session packet repeats the circuit's skeleton every 0.5 s: track length, sector 2/3 start distances, up to
21 marshal-zone starts and, in UDP format 2026, DRS and full/partial active-aero zones. Those are the game's scoring
data, so they are exact by definition for pitwall's purposes (docs/research/track-knowledge-sources.md section 2,
"Sectors and zones: always L0a"). This module turns the wire values (``model.TrackZones``) into a lap-distance
skeleton the coach, dashboard and engineer can query.

Design decisions:

* **Metres = fraction x game track length.** The EA spec gives zones as fractions of ``m_trackLength``; the game's
  ``m_lapDistance`` is in the same metres, so no alignment step is needed.
* **Cyclic positions.** A lap is a circle of length L: positions are taken modulo L, so the line is 0 (a distance of
  exactly L *is* the line), and F1's negative lap distance before the first line crossing (``-d`` = d metres before
  the line) maps to ``L - d``. Values more than one lap outside ``[0, L)`` are not a position on this lap -> None.
* **Wrap-aware zones without splitting identity.** A zone keeps one ``start_m``/``end_m`` (``end_m < start_m`` means
  it runs through the line) plus ``segments_m``: one or two non-wrapping ``[a, b)`` pieces for drawing and lookups.
  Marshal zones carry only a start; each runs to the next start in lap order, so the last one wraps (Austria: the
  zone starting at 0.9908 covers the line and ends at 0.0792).
* **Unknown stays unknown.** Missing or inconsistent inputs give ``None`` (e.g. S2 after S3, no track length), never
  a fabricated boundary. ``None`` zone tables mean "not reported" and differ from an empty tuple ("zero zones").
  Zero-length zones, including ``(1.0, 1.0)`` and float32 noise either side of the line, are dropped rather than
  read as a zone that covers the whole lap.
* **Geometry, not timing.** ``sector_of`` and the zone lookups say where a point lies on the circuit. They are not
  the game's timing state for a car (see ``sector_of``): timing consumers use ``CarFrame.sector``.
* **Flags are live state.** Marshal flags are meaningful only in the live skeleton (``build_track_skeleton``). A
  stored session row is a snapshot taken whenever other session info changed, so ``skeleton_from_session_row``
  drops its flags (unknown) instead of replaying one arbitrary moment as a fact about the session.
* **Identifiers are the game's.** ``Zone.index`` is the game's array position; ``game_number`` (index + 1) is what
  to show or say ("marshal zone 1", "DRS 1"), matching flags and race-control messages. ``lap_order`` is only the
  order of starts from the line, for drawing and tie-breaks; it is never shown as a zone's name.
* **Evidence tiers.** A skeleton built from a synthetic session is tiered ``synthetic``, never ``game_native``, so no
  consumer can present generated zones as game data.
* **Pure and cheap.** No I/O, O(zones). Safe to call from the live snapshot path, but callers should still cache by
  ``TrackZones.geometry_key()`` plus flags rather than rebuild per frame.
"""

from __future__ import annotations

import math
from bisect import bisect_right
from collections.abc import Mapping, Sequence
from dataclasses import dataclass
from enum import StrEnum
from typing import Any

from pitwall.model.synthetic import SYNTHETIC_SESSION_UID
from pitwall.model.telemetry import FracZone, MarshalZone, SessionInfo, TrackZones

TIER_GAME_NATIVE = "game_native"  # provenance tier (track-knowledge-sources.md "Representing confidence")
TIER_SYNTHETIC = "synthetic"  # generated by pitwall.sim: never evidence of what a game sends
FRAC_TOLERANCE = 1e-6  # float32 lap fractions may sit a hair outside [0, 1]
_M_DECIMALS = 2  # to_dict() rounding: centimetres (the game's own values are float32)
_FRAC_DECIMALS = 6


class ZoneKind(StrEnum):
    MARSHAL = "marshal"
    DRS = "drs"
    AERO_FULL = "aero_full"  # active-aero zones when the track status is "full"
    AERO_PARTIAL = "aero_partial"  # active-aero zones when the track status is "partial"


@dataclass(frozen=True, slots=True)
class Sector:
    index: int  # 0-based (S1 = 0): the same numbering as LapData.sector / CarFrame.sector
    start_m: float
    end_m: float

    @property
    def name(self) -> str:
        return f"S{self.index + 1}"

    @property
    def length_m(self) -> float:
        return self.end_m - self.start_m


@dataclass(frozen=True, slots=True)
class Zone:
    """A stretch of the lap.

    ``wraps`` (two segments) means it runs through the start/finish line, normally shown by ``end_m < start_m``; the
    one exception is a lone marshal zone that covers the whole lap from a start past the line (``end_m == start_m``).
    ``segments_m`` never wraps, so drawing and lookups need no modular arithmetic.
    """

    kind: ZoneKind
    index: int  # position in the game's array: the zone's identity (flags and race-control messages refer to it)
    lap_order: int  # 1-based order of starts from the line; for drawing / tie-breaks only, never a zone's name
    start_m: float  # [0, L)
    end_m: float  # (0, L]
    length_m: float
    segments_m: tuple[tuple[float, float], ...]  # 1 or 2 half-open [a, b) pieces; empty for a zero-length zone
    flag: str | None = None  # marshal zones only: "none" | "green" | "blue" | "yellow" | None (unknown)

    @property
    def wraps(self) -> bool:
        return len(self.segments_m) > 1

    @property
    def game_number(self) -> int:
        """1-based game identifier (index + 1): the number to show or speak ("marshal zone 1")."""
        return self.index + 1

    def contains(self, position_m: float) -> bool:
        """``position_m`` must be a normalised lap position in [0, L) (see ``TrackSkeleton.position_m``)."""
        return any(a <= position_m < b for a, b in self.segments_m)

    def to_dict(self, track_length_m: float) -> dict[str, Any]:
        return {
            "kind": self.kind.value,
            "index": self.index,
            "game_number": self.game_number,
            "lap_order": self.lap_order,
            "start_m": round(self.start_m, _M_DECIMALS),
            "end_m": round(self.end_m, _M_DECIMALS),
            "length_m": round(self.length_m, _M_DECIMALS),
            "start_frac": round(self.start_m / track_length_m, _FRAC_DECIMALS),
            "end_frac": round(self.end_m / track_length_m, _FRAC_DECIMALS),
            "wraps": self.wraps,
            "segments_m": [[round(a, _M_DECIMALS), round(b, _M_DECIMALS)] for a, b in self.segments_m],
            "flag": self.flag,
        }


@dataclass(frozen=True, slots=True, kw_only=True)
class TrackSkeleton:
    """Game-native lap skeleton in metres. Build with ``build_track_skeleton`` or ``TrackSkeleton.from_zones``."""

    track_length_m: float | None = None
    sector2_start_m: float | None = None
    sector3_start_m: float | None = None
    marshal_zones: tuple[Zone, ...] | None = None  # sorted by start; together they cover the whole lap
    drs_zones: tuple[Zone, ...] | None = None
    aero_full_zones: tuple[Zone, ...] | None = None
    aero_partial_zones: tuple[Zone, ...] | None = None
    active_aero_track_status: str | None = None  # "full" | "partial" (which aero table is in force)
    pit_speed_limit_kph: float | None = None
    game: str | None = None
    track_id: str | None = None
    source: str | None = None  # wire format it was decoded from, e.g. "f1_session@2025" (also for synthetic streams)
    tier: str = TIER_GAME_NATIVE  # TIER_GAME_NATIVE | TIER_SYNTHETIC: the evidence tier, check this, not ``source``

    # ------------------------------------------------------------------ construction
    @classmethod
    def from_zones(
        cls,
        track_length_m: float | None,
        zones: TrackZones | None,
        *,
        pit_speed_limit_kph: float | None = None,
        game: str | None = None,
        track_id: str | None = None,
        synthetic: bool = False,
        live_flags: bool = True,
    ) -> TrackSkeleton:
        """Validate and convert the game's zone tables. Never raises on bad input; bad parts become ``None``.

        ``synthetic`` tiers the result ``synthetic``. ``live_flags=False`` drops the marshal flags (unknown), for any
        input that is not the current live Session packet.
        """
        length = _positive(track_length_m)
        z = zones or TrackZones()
        if not live_flags:
            z = z.without_flags()
        s2, s3 = _sector_starts(z.sector2_start_m, z.sector3_start_m, length)
        return cls(
            track_length_m=length,
            sector2_start_m=s2,
            sector3_start_m=s3,
            marshal_zones=_marshal_zones(z.marshal_zones, length),
            drs_zones=_span_zones(z.drs_zones_frac, length, ZoneKind.DRS),
            aero_full_zones=_span_zones(z.aero_full_zones_frac, length, ZoneKind.AERO_FULL),
            aero_partial_zones=_span_zones(z.aero_partial_zones_frac, length, ZoneKind.AERO_PARTIAL),
            active_aero_track_status=z.active_aero_track_status,
            pit_speed_limit_kph=_positive(pit_speed_limit_kph),
            game=game,
            track_id=track_id,
            source=z.source,
            tier=TIER_SYNTHETIC if synthetic else TIER_GAME_NATIVE,
        )

    # ------------------------------------------------------------------ sectors
    @property
    def sector_boundaries_m(self) -> tuple[float, float, float, float] | None:
        """``(0, S2 start, S3 start, L)`` when all are known and consistent, else ``None``."""
        if self.track_length_m is None or self.sector2_start_m is None or self.sector3_start_m is None:
            return None
        return (0.0, self.sector2_start_m, self.sector3_start_m, self.track_length_m)

    @property
    def sectors(self) -> tuple[Sector, Sector, Sector] | None:
        b = self.sector_boundaries_m
        if b is None:
            return None
        return (Sector(0, b[0], b[1]), Sector(1, b[1], b[2]), Sector(2, b[2], b[3]))

    def position_m(self, distance_m: float | None) -> float | None:
        """Normalise a lap distance to a position in ``[0, L)`` (see module docstring for the cyclic rules)."""
        if distance_m is None or not math.isfinite(distance_m):
            return None
        length = self.track_length_m
        if length is None:
            return float(distance_m) if distance_m >= 0 else None  # cannot wrap without a length
        if distance_m < -length or distance_m >= 2 * length:
            return None  # more than a lap away from this lap: not a position on it (e.g. a garage placeholder)
        p = distance_m % length
        return 0.0 if p >= length else p  # float edge: (-1e-18) % L == L

    def fraction(self, distance_m: float | None) -> float | None:
        p = self.position_m(distance_m)
        return None if p is None or self.track_length_m is None else p / self.track_length_m

    @property
    def synthetic(self) -> bool:
        return self.tier == TIER_SYNTHETIC

    def sector_of(self, distance_m: float | None) -> int | None:
        """0-based sector of *track* that ``distance_m`` lies on: geometry, not timing.

        A boundary belongs to the sector it starts (S2 start -> 1); positions are cyclic (module docstring), so 10 m
        before the line is on the S3 stretch and 0.2 m past it is on S1. This is NOT the sector the game is timing
        for a car. On the line-crossing frame real F1 25 reports lapDistance 4323.23 m (> L) with S3 (2) still
        running (PS5 Austria capture). On lap 1 before the first crossing (negative lapDistance; not in any recording
        yet) the game most likely reports S1 (0). Use this to place things on the lap (corners, brake points, chart
        cursors); use ``CarFrame.sector`` for splits, deltas and anything about the timing of a lap.
        """
        s2, s3 = self.sector2_start_m, self.sector3_start_m
        if s2 is None or s3 is None:
            return None
        p = self.position_m(distance_m)
        return None if p is None else bisect_right((s2, s3), p)

    # ------------------------------------------------------------------ zones
    def zones(self, kind: ZoneKind) -> tuple[Zone, ...] | None:
        return {
            ZoneKind.MARSHAL: self.marshal_zones,
            ZoneKind.DRS: self.drs_zones,
            ZoneKind.AERO_FULL: self.aero_full_zones,
            ZoneKind.AERO_PARTIAL: self.aero_partial_zones,
        }[kind]

    def zone_at(self, kind: ZoneKind, distance_m: float | None) -> Zone | None:
        """The zone of ``kind`` containing ``distance_m`` (None if outside every zone or unknown)."""
        zs = self.zones(kind)
        p = self.position_m(distance_m)
        if not zs or p is None:
            return None
        return next((z for z in zs if z.contains(p)), None)

    def marshal_zone_at(self, distance_m: float | None) -> Zone | None:
        return self.zone_at(ZoneKind.MARSHAL, distance_m)

    def drs_zone_at(self, distance_m: float | None) -> Zone | None:
        return self.zone_at(ZoneKind.DRS, distance_m)

    def next_zone(self, kind: ZoneKind, distance_m: float | None) -> tuple[Zone, float] | None:
        """The next zone of ``kind`` starting at or ahead of ``distance_m`` (cyclic) and the metres to its start."""
        zs = self.zones(kind)
        p = self.position_m(distance_m)
        if not zs or p is None or self.track_length_m is None:
            return None
        length = self.track_length_m
        return min(((z, (z.start_m - p) % length) for z in zs), key=lambda zd: (zd[1], zd[0].lap_order))

    # ------------------------------------------------------------------ export
    def to_dict(self) -> dict[str, Any]:
        """Strict-JSON-safe payload for the API / live snapshot (key ``skeleton``)."""
        length = self.track_length_m
        sectors = self.sectors

        def zones(zs: tuple[Zone, ...] | None) -> list[dict[str, Any]] | None:
            return None if zs is None or length is None else [z.to_dict(length) for z in zs]

        def m(v: float | None) -> float | None:
            return None if v is None else round(v, _M_DECIMALS)

        return {
            "tier": self.tier,
            "synthetic": self.synthetic,
            "source": self.source,
            "game": self.game,
            "track_id": self.track_id,
            "track_length_m": m(length),
            "pit_speed_limit_kph": self.pit_speed_limit_kph,
            "sector2_start_m": m(self.sector2_start_m),
            "sector3_start_m": m(self.sector3_start_m),
            "sector_boundaries_m": None if sectors is None else [m(v) for v in self.sector_boundaries_m or ()],
            "sectors": None
            if sectors is None
            else [
                {
                    "index": s.index,
                    "name": s.name,
                    "start_m": m(s.start_m),
                    "end_m": m(s.end_m),
                    "length_m": m(s.length_m),
                }
                for s in sectors
            ],
            "marshal_zones": zones(self.marshal_zones),
            "drs_zones": zones(self.drs_zones),
            "aero_full_zones": zones(self.aero_full_zones),
            "aero_partial_zones": zones(self.aero_partial_zones),
            "active_aero_track_status": self.active_aero_track_status,
        }


# ---------------------------------------------------------------------- public builders
def build_track_skeleton(info: SessionInfo) -> TrackSkeleton:
    """Skeleton for the live/decoded session, flags included. Fields the game does not send stay ``None``.

    Synthetic sessions are recognised by any of the markers pitwall puts on them: the session manager's
    ``extra["synthetic"]``, the generator's ``SYNTHETIC_SESSION_UID`` (already set by the adapter, so this also holds
    before the session manager has seen the info) or a ``synthetic:`` track id.
    """
    return TrackSkeleton.from_zones(
        info.track_length_m,
        info.track_zones,
        pit_speed_limit_kph=info.pit_speed_limit_kph,
        game=info.game.value,
        track_id=info.track_id,
        synthetic=bool(info.extra.get("synthetic"))
        or info.session_uid == str(SYNTHETIC_SESSION_UID)
        or _synthetic_track_id(info.track_id),
    )


def skeleton_from_session_row(row: Mapping[str, Any]) -> TrackSkeleton | None:
    """Skeleton for a stored session row (``storage.repo.get_session``), old or new.

    New rows carry ``info["track_zones"]`` (``TrackZones.to_dict()``); rows written before the typed zones only have
    the legacy ``info["sector2_start_m"]`` / ``info["sector3_start_m"]`` keys, which still give the sector bands.
    Returns ``None`` when the row has nothing skeleton-like at all.

    Marshal flags are always dropped (unknown): a stored copy is one 0.5 s moment, not the session's flag history.
    The tier is ``synthetic`` when the row (``synthetic`` column), its info or its track id says so.
    """
    info = row.get("info")
    info = info if isinstance(info, Mapping) else {}
    zones = TrackZones.from_dict(info.get("track_zones"))
    if zones is None:
        s2, s3 = _num(info.get("sector2_start_m")), _num(info.get("sector3_start_m"))
        if s2 is None and s3 is None:
            return None
        zones = TrackZones(source="legacy_session_info", sector2_start_m=s2, sector3_start_m=s3)
    track_id = row.get("track_id") if isinstance(row.get("track_id"), str) else None
    return TrackSkeleton.from_zones(
        _num(row.get("track_length_m")),
        zones,
        pit_speed_limit_kph=_num(info.get("pit_speed_limit_kph")),
        game=row.get("game") if isinstance(row.get("game"), str) else None,
        track_id=track_id,
        synthetic=bool(row.get("synthetic")) or bool(info.get("synthetic")) or _synthetic_track_id(track_id),
        live_flags=False,
    )


# ---------------------------------------------------------------------- validation / conversion
def _synthetic_track_id(track_id: str | None) -> bool:
    return track_id is not None and track_id.startswith("synthetic:")


def _num(v: Any) -> float | None:
    return float(v) if isinstance(v, int | float) and not isinstance(v, bool) and math.isfinite(v) else None


def _positive(v: float | None) -> float | None:
    return float(v) if v is not None and math.isfinite(v) and v > 0 else None


def _sector_starts(s2: float | None, s3: float | None, length: float | None) -> tuple[float | None, float | None]:
    """Keep each start only if it lies strictly inside the lap; drop both if they contradict each other."""

    def inside(v: float | None) -> float | None:
        if v is None or not math.isfinite(v) or v <= 0:
            return None
        return v if length is None or v < length else None

    a, b = inside(s2), inside(s3)
    if a is not None and b is not None and a >= b:
        return None, None  # S2 must start before S3; which one is wrong is unknowable
    return a, b


def _frac(v: float) -> float | None:
    """A lap fraction clamped into [0, 1] within float32 tolerance; anything else is invalid."""
    if not math.isfinite(v) or v < -FRAC_TOLERANCE or v > 1 + FRAC_TOLERANCE:
        return None
    return min(1.0, max(0.0, v))


def _segments(start_m: float, end_m: float, length: float) -> tuple[tuple[float, float], ...]:
    if end_m > start_m:
        return ((start_m, end_m),)
    if end_m < start_m:
        return ((start_m, length), (0.0, end_m)) if end_m > 0 else ((start_m, length),)
    return ()


def _span(start_f: float, end_f: float, length: float) -> tuple[float, float] | None:
    """(start_m in [0, L), end_m in (0, L]) for a (start, end) fraction pair; None if invalid or zero-length.

    Zero-length is decided on the clamped fractions *before* the line is folded (``1.0 % 1.0 == 0``): otherwise
    ``(1.0, 1.0)`` or float32 noise such as ``(1.0000003, 0.9999999)`` would become start 0, end L, a zone covering
    the whole lap. ``(0.0, 1.0)`` stays a genuine whole-lap zone.
    """
    a, b = _frac(start_f), _frac(end_f)
    if a is None or b is None or math.isclose(a, b, abs_tol=FRAC_TOLERANCE):
        return None
    start_m = (a % 1.0) * length  # a start of 1.0 is the line
    end_m = b * length
    if end_m == 0.0 and start_m > 0.0:
        end_m = length  # ending exactly at the line: the end of this lap, not a wrap
    if math.isclose(start_m, end_m, abs_tol=1e-9):
        return None  # (1.0, 0.0): from the line to the line
    zone_length = end_m - start_m if end_m > start_m else length - start_m + end_m
    if zone_length < FRAC_TOLERANCE * length:
        return None  # noise either side of the line, e.g. (0.9999995, 0.0000003)
    return start_m, end_m


def _zone(
    kind: ZoneKind,
    index: int,
    lap_order: int,
    start: float,
    end: float,
    segs: tuple[tuple[float, float], ...],
    flag: str | None,
) -> Zone:
    return Zone(kind, index, lap_order, start, end, sum(b - a for a, b in segs), segs, flag)


def _numbered(kind: ZoneKind, spans: list[tuple[int, float, float, str | None]], length: float) -> tuple[Zone, ...]:
    """Sort (index, start, end, flag) by start along the lap and build ``Zone``s with ``lap_order`` 1..n."""
    spans.sort(key=lambda s: (s[1], s[0]))
    return tuple(
        _zone(kind, idx, n, start, end, _segments(start, end, length), flag)
        for n, (idx, start, end, flag) in enumerate(spans, start=1)
    )


def _span_zones(pairs: Sequence[FracZone] | None, length: float | None, kind: ZoneKind) -> tuple[Zone, ...] | None:
    """DRS / active-aero zones: explicit (start, end) pairs. Invalid or zero-length pairs are dropped."""
    if pairs is None or length is None:
        return None  # not reported, or not convertible to metres
    spans: list[tuple[int, float, float, str | None]] = []
    for i, (s, e) in enumerate(pairs):
        span = _span(s, e, length)
        if span is not None:
            spans.append((i, span[0], span[1], None))
    return _numbered(kind, spans, length)


def _marshal_zones(zones: Sequence[MarshalZone] | None, length: float | None) -> tuple[Zone, ...] | None:
    """Marshal zones: starts only. Each zone ends where the next one (in lap order) starts; the last one wraps."""
    if zones is None or length is None:
        return None
    starts: list[tuple[int, float, str | None]] = []
    for i, z in enumerate(zones):
        f = _frac(z.start_frac)
        if f is not None:
            starts.append((i, (f % 1.0) * length, z.flag))
    if not starts:
        return ()
    starts.sort(key=lambda s: (s[1], s[0]))
    if len(starts) == 1:  # a single zone covers the whole lap, from its start round to itself
        idx, start, flag = starts[0]
        segs = ((start, length), (0.0, start)) if start > 0 else ((0.0, length),)
        return (_zone(ZoneKind.MARSHAL, idx, 1, start, start if start > 0 else length, segs, flag),)
    spans: list[tuple[int, float, float, str | None]] = []
    for k, (idx, start, flag) in enumerate(starts):
        nxt = starts[(k + 1) % len(starts)][1]
        end = length if (k == len(starts) - 1 and nxt == 0.0) else nxt
        spans.append((idx, start, end, flag))
    return _numbered(ZoneKind.MARSHAL, spans, length)
