"""Read-only MCP server that lets Claude Code consult the local Qwen model during development.

Claude Code cannot swap its own model to a local llama.cpp model in a supported way, so Qwen is exposed as
*tools* Claude can call for second opinions: code review, test ideas, and general questions.

Safety design:
* Read-only: tools read project files (confined to the project root, secrets/VCS/data deny-listed) and return
  text. Nothing here writes files or runs code. Qwen output is labelled ADVISORY; Claude must review and test
  before using any of it (see CLAUDE.md).
* Loopback only: the LLM endpoint must be on this machine.
* One request at a time, and refuses while a real (non-synthetic) race session is live in Pitwall, so dev
  tooling never competes with the race engineer for the shared model.

Run by Claude Code via ``.mcp.json``. Manual smoke test:
``uv run --extra devtools python -m pitwall.devtools.qwen_mcp``.
"""

from __future__ import annotations

import asyncio
import logging
import os
from pathlib import Path
from urllib.parse import urlparse

import httpx
from mcp.server import MCPServer
from mcp.server.mcpserver.exceptions import ToolError
from mcp.types import ToolAnnotations

log = logging.getLogger("pitwall.qwen_mcp")  # stderr only; stdout carries JSON-RPC

ROOT = Path(os.environ.get("CLAUDE_PROJECT_DIR") or Path(__file__).resolve().parents[3]).resolve()
BASE_URL = os.environ.get("QWEN_BASE_URL", "http://127.0.0.1:8081/v1").rstrip("/")
PITWALL_URL = os.environ.get("PITWALL_URL", "http://127.0.0.1:8770")
DENY_PARTS = {".git", ".venv", "node_modules", "data", "secrets", "__pycache__"}
MAX_FILE_BYTES = 120_000
MAX_TOTAL_CHARS = 60_000
TIMEOUT_S = float(os.environ.get("QWEN_TIMEOUT_S", "300"))
ADVISORY = "[ADVISORY - generated by local Qwen; unverified. Review and test before acting on it.]\n\n"

if urlparse(BASE_URL).hostname not in {"127.0.0.1", "localhost", "::1"}:
    raise SystemExit("QWEN_BASE_URL must point at a loopback address")

mcp = MCPServer(
    "qwen",
    instructions=(
        "Second opinions from the local Qwen model (llama.cpp on this Mac). Slow: typically 15 s - 3 min per "
        "call. Output is ADVISORY and unverified. Use for independent review, test ideas and repetitive "
        "drafting; Claude remains responsible for design decisions and validation."
    ),
    log_level="WARNING",
)
READ_ONLY = ToolAnnotations(read_only_hint=True, destructive_hint=False, idempotent_hint=True, open_world_hint=False)
_one_at_a_time = asyncio.Semaphore(1)


def read_project_file(rel: str) -> str:
    p = (ROOT / rel).resolve()
    if not p.is_relative_to(ROOT):
        raise ToolError(f"{rel!r} is outside the project")
    parts = set(p.relative_to(ROOT).parts)
    if parts & DENY_PARTS or p.name.startswith(".env") or p.suffix in {".pem", ".key", ".sqlite3"}:
        raise ToolError(f"{rel!r} is deny-listed")
    if not p.is_file():
        raise ToolError(f"{rel!r} does not exist")
    if p.stat().st_size > MAX_FILE_BYTES:
        raise ToolError(f"{rel!r} is larger than {MAX_FILE_BYTES} bytes")
    return p.read_text(encoding="utf-8", errors="replace")


async def _race_is_live() -> bool:
    try:
        async with httpx.AsyncClient(timeout=1.0) as c:
            h = (await c.get(f"{PITWALL_URL}/api/health")).json()
        conn = h.get("connection", {})
        return conn.get("status") == "live" and not conn.get("synthetic")
    except Exception:
        return False


async def _chat(system: str, user: str, max_tokens: int) -> str:
    if await _race_is_live():
        raise ToolError("a live race session is running in Pitwall; Qwen is reserved for the race engineer")
    if len(user) > MAX_TOTAL_CHARS:
        raise ToolError(f"request too large ({len(user)} chars > {MAX_TOTAL_CHARS}); send fewer/smaller files")
    async with _one_at_a_time, httpx.AsyncClient(timeout=TIMEOUT_S) as c:
        try:
            models = (await c.get(f"{BASE_URL}/models")).json()["data"]
            body = {
                "model": models[0]["id"],
                "messages": [{"role": "system", "content": system}, {"role": "user", "content": user}],
                "max_tokens": max_tokens,
                "temperature": 0.2,
            }
            r = await c.post(f"{BASE_URL}/chat/completions", json=body)
            r.raise_for_status()
            return str(r.json()["choices"][0]["message"]["content"]).strip()
        except (httpx.HTTPError, KeyError, IndexError, ValueError) as e:
            raise ToolError(f"local Qwen unavailable: {type(e).__name__}: {e}") from e


def _files_block(paths: list[str]) -> str:
    out = []
    for rel in paths:
        out.append(f"### FILE: {rel}\n```\n{read_project_file(rel)}\n```")
    return "\n\n".join(out)


@mcp.tool(annotations=READ_ONLY)
async def qwen_status() -> str:
    """Report whether the local Qwen endpoint is reachable and which model it serves."""
    try:
        async with httpx.AsyncClient(timeout=5) as c:
            data = (await c.get(f"{BASE_URL}/models")).json()["data"]
        live = await _race_is_live()
        return f"endpoint {BASE_URL}: model {data[0]['id']}; race live: {live}"
    except Exception as e:
        return f"endpoint {BASE_URL} unreachable: {type(e).__name__}: {e}"


@mcp.tool(annotations=READ_ONLY)
async def qwen_ask(question: str, context: str = "") -> str:
    """Ask the local Qwen model a general engineering question (advisory answer)."""
    ans = await _chat(
        "You are a careful senior Python engineer. Be concise and concrete. Say when you are unsure.",
        f"{context}\n\nQUESTION: {question}".strip(),
        800,
    )
    return ADVISORY + ans


@mcp.tool(annotations=READ_ONLY)
async def qwen_review_code(paths: list[str], focus: str = "correctness bugs") -> str:
    """Independent code review by local Qwen of project files (paths relative to the repo root).

    Returns a numbered list of suspected issues with file/line references. Advisory only.
    """
    if not paths:
        raise ToolError("give at least one path")
    files = _files_block(paths)
    ans = await _chat(
        "You are reviewing code for a real-time sim-racing telemetry app (Python 3.12). Report only concrete, "
        "verifiable problems (bugs, unit errors, off-by-one, threading/race issues, unhandled edge cases). "
        "For each: file, approximate line, the problem, and a concrete failure scenario. No style nitpicks. "
        "If you find nothing solid, say so.",
        f"FOCUS: {focus}\n\n{files}",
        1200,
    )
    return ADVISORY + ans


@mcp.tool(annotations=READ_ONLY)
async def qwen_generate_tests(path: str, target: str = "", existing_tests: str = "") -> str:
    """Ask local Qwen to PROPOSE pytest tests for a module. Returns code as text; never writes files."""
    files = _files_block([path] + ([existing_tests] if existing_tests else []))
    ans = await _chat(
        "You write focused pytest tests (Python 3.12, pytest, no network). Cover edge cases and failure modes. "
        "Return a single python code block plus a one-line rationale per test.",
        f"TARGET: {target or 'the public functions in the module'}\n\n{files}",
        1600,
    )
    return ADVISORY + ans


def main() -> None:
    logging.basicConfig(level=logging.WARNING)
    mcp.run()  # stdio transport


if __name__ == "__main__":
    main()
