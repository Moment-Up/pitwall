def test_8nm_keeps_the_in_game_strength_except_comfort() -> None:
    """Research revision 2: no source lowers in-game strength going from 5 to 8 Nm; only Comfort scales by 5/8."""

    def strength(game: str, style: str, torque: int) -> SettingRow:
        return row(recommend(game, Hardware(torque_nm=torque), style, "advanced"), STRENGTH_KEY[game])

    for style in ("official_default", "balanced", "realism"):
        assert strength("f1_25", style, 5).value == strength("f1_25", style, 8).value
    comfort5, comfort8 = strength("f1_25", "comfort", 5), strength("f1_25", "comfort", 8)
    assert (comfort5.value, comfort8.value) == ("60", "40") and comfort8.provenance.derived
    assert round_to(60 * 5 / 8, 5) == 40 and round_to(32.5, 5) == 35
    assert (strength("f1_25", "competitive", 5).value, strength("f1_25", "competitive", 8).value) == ("90", "95")
    for style in STYLES:
        assert strength("gt7", style, 5).value == strength("gt7", style, 8).value  # GT7's scale is never rescaled
    # realism at 8 Nm keeps F1withNick's 60 by the keep rule: a pitwall application, labelled D
    assert strength("f1_25", "realism", 8).provenance.derived


@pytest.mark.parametrize("game", ["f1_25", "gt7"])
@pytest.mark.parametrize("style", STYLES)
def test_8nm_force_text_matches_what_the_table_did(game: str, style: str) -> None:
    """Finding 2: the safety box and the Boost Kit step may only say "lowered" when the value really is lower, and
    never that something was already reduced."""
    key = STRENGTH_KEY[game]
    at5 = row(recommend(game, Hardware(), style, "intermediate"), key)
    rec = recommend(game, Hardware(torque_nm=8), style, "intermediate")
    at8 = row(rec, key)
    safety = next(s.text for s in rec.safety if s.id == "boost_kit_force")
    step = next(s.text for s in rec.sections[0].steps if s.id == "strength")
    n5, n8 = float(at5.value), float(at8.value)
    for text in (safety, step):
        assert "already" not in text
        if n8 < n5:
            assert f"lowered from {at5.value} to {at8.value}" in text
        else:
            assert "lowered" not in text
        if n8 == n5:
            assert f"stays at {at8.value}" in text
        if n8 > n5:
            assert f"goes up from {at5.value} to {at8.value}" in text
    _text, _ev, change = strength_at_8nm(CAT, game, rec.style)
    assert change == ("lowered" if n8 < n5 else "kept" if n8 == n5 else "raised")
    adv = recommend(game, Hardware(torque_nm=8), style, "advanced")
    assert "boost_kit_force" not in {s.id for s in adv.safety}
    assert next(s.text for s in adv.sections[0].steps if s.id == "strength") == step


