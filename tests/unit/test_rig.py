HZ = 60.0
Spec = dict[str, Any]


def synth_lap(
    segments: list[tuple[float, Spec]],
    lap_number: int = 1,
    extra: dict[str, Any] | None = None,
    flags: set[str] | None = None,
) -> LapTrace:
    """Concatenate segments of (seconds, {channel: constant | f(t_in_segment)}) sampled at 60 Hz."""
    cols: dict[str, list[float]] = {k: [] for k in ("throttle", "brake", "steering", "speed_kph", "g_lat")}
    extra_cols: dict[str, list[float]] = {k: [] for k in (extra or {})}
    for seconds, spec in segments:
        n = round(seconds * HZ)
        tt = np.arange(n) / HZ
        for k, col in (*cols.items(), *extra_cols.items()):
            v = spec.get(k, (extra or {}).get(k, 0.0))
            col.extend(np.broadcast_to(v(tt) if callable(v) else v, (n,)).astype(float).tolist())
    n = len(cols["brake"])
    t = 100.0 + np.arange(n) / HZ
    speed = np.asarray(cols["speed_kph"])
    channels = {k: np.asarray(v, dtype=float) for k, v in (*cols.items(), *extra_cols.items())}
    channels["session_time_s"] = t
    channels["distance_m"] = np.cumsum(speed / 3.6 / HZ)
    return LapTrace(lap_number, channels, int(n / HZ * 1000), valid=True, flags=set(flags or ()))


STRAIGHT: Spec = {"throttle": 1.0, "speed_kph": 300.0, "steering": 0.002}
CORNER: Spec = {"throttle": 0.5, "speed_kph": 100.0, "steering": 0.3, "g_lat": 2.0}


def ramp(peak: float = 1.0, n: int = 18) -> Callable[[np.ndarray[Any, Any]], np.ndarray[Any, Any]]:
    return lambda tt: np.minimum(peak, (np.arange(len(tt)) + 1) / n * peak)


def braking(hold_s: float = 1.0, *, dip: bool = False, peak: float = 1.0) -> list[tuple[float, Spec]]:
    """Ramp 0 -> peak over 18 samples, hold, release linearly over 1.0 s (60 samples); entry at 300 km/h."""
    hold: Spec = {"brake": peak, "speed_kph": 200.0}
    if dip:  # release to 80% and re-apply in the middle of the hold
        hold["brake"] = lambda tt: np.where((tt > 0.3) & (tt < 0.6), 0.8 * peak, peak)
    return [
        (0.3, {"brake": ramp(peak), "speed_kph": 300.0}),
        (hold_s, hold),
        (1.0, {"brake": lambda tt: np.maximum(0.0, peak - (np.arange(len(tt)) + 1) / 60.0 * peak), "speed_kph": 110.0}),
    ]


def standard_lap(**kw: Any) -> LapTrace:
    straight = {**STRAIGHT, **kw.pop("straight", {})}
    return synth_lap([(6.0, straight), *braking(**kw), (3.0, CORNER), (6.0, {**straight, "speed_kph": 250.0})])


def metric(laps: list[LapTrace], name: str, game: str | None = "f1_25", **kw: Any) -> MetricResult:
    return next(m for m in run_rig_check(laps, game=game, **kw) if m.metric == name)


def value(m: MetricResult) -> float:
    assert m.value is not None, m.reason_unknown
    return m.value


