@pytest.mark.parametrize("hz", [1.0, 2.0, 4.0, 8.0, 20.0])
def test_brake_hold_noise_catches_a_periodic_oscillation(hz: float) -> None:
    """Review major: the research statistic is the std of the brake in a hold. A +-3% sine (std 2.12%, over the 2%
    limit) must warn at any frequency from 1 Hz; the old sample-to-sample estimate read 0.3% at 2 Hz and passed."""
    hold: Spec = {"brake": lambda tt: 0.5 + 0.03 * np.sin(2 * np.pi * hz * tt), "speed_kph": 150.0, "throttle": 0.0}
