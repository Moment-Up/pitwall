def test_api_rig_check_prefers_real_sessions_and_matches_the_baseline_tier(
    api: tuple[TestClient, SimpleNamespace], clean_session: DecodedSession
) -> None:
    client, rt = api
    james = _add_driver(rt, "James", "advanced")
    laps = [lap for lap in clean_session.laps if lap.clean]
    # The laps are generated, but the sessions' evidence tier is what the selection must respect.
    _add_session(rt, "real_before", laps, james, synthetic=False)
    _shift_start(rt, "real_before", -7200)
    _add_session(rt, "synth_before", laps, james, synthetic=True)
    _shift_start(rt, "synth_before", -3600)
    client.post("/api/rig/upgrades", json={"change": "load_cell_kit"})
    _add_session(rt, "real_after", laps, james, synthetic=False)
    _add_session(rt, "synth_after", laps, james, synthetic=True)
    _shift_start(rt, "synth_after", 60)  # the most recent session is synthetic
    body = client.get("/api/rig/check", params={"driver_id": james, "baseline": "upgrade"}).json()
    assert body["session_id"] == "real_after" and not body["synthetic"]  # a synthetic session is never the default
    assert body["baseline"]["session_id"] == "real_before" and not body["baseline"]["synthetic"]
    # the pedals in use come from the upgrade history: the load-cell checks know which session had which brake
    assert body["pedals"] == "csl_load_cell" and body["baseline"]["pedals"] == "csl"
    history = {m["metric"]: m for m in body["metrics"]}["brake_peak_vs_history"]
    assert history["status"] == "unknown" and "BRF" in history["reason_unknown"]
    before = {m["metric"]: m for m in body["baseline"]["metrics"]}["brake_peak_vs_history"]
    assert "Hall" in before["reason_unknown"]
    synth = client.get("/api/rig/check", params={"session_id": "synth_after", "baseline": "upgrade"}).json()
    assert synth["synthetic"] and synth["baseline"]["session_id"] == "synth_before"  # same tier, same driver
    # only synthetic sessions: shown (flagged), never hidden
    sam = _add_driver(rt, "Sam", "beginner")
    _add_session(rt, "sam_synth", laps, sam, synthetic=True)
    only = client.get("/api/rig/check", params={"driver_id": sam}).json()
    assert only["session_id"] == "sam_synth" and only["synthetic"] and only["notes"][0].startswith("SYNTHETIC")


