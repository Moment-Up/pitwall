def test_every_recommended_value_is_backed_by_what_its_sources_publish() -> None:
    """The provenance invariant behind review finding 6: a value is never labelled more certain than the published
    value behind it, and a start value picked inside a published range is pitwall's (D)."""
    for e in CAT.wheel_entries.values():
        for key, b in e.backing.items():
            v = e.value(key)
            assert v is not None
            if b.kind == "derived":
                assert b.evidence == "D"
            elif b.kind == "sourced":
                published = [CAT.presets[p].setting(key) for p in b.presets]
                assert any(sv is not None and sv.same_value(v) for sv in published), (e.id, key)
                best = max(EVIDENCE_RANK[sv.evidence] for sv in published if sv is not None and sv.same_value(v))
                assert EVIDENCE_RANK[b.evidence] <= min(best, EVIDENCE_RANK[v.evidence]), (e.id, key)
            elif b.kind == "range_pick":
                assert b.evidence == "D" and b.range_evidence in ("V", "A", "U")
                assert v.number is not None
                assert any((sv := CAT.presets[p].setting(key)) and sv.contains(v.number) for p in b.presets)
            elif b.kind == "instruction":
                assert key in CAT.instructions
            if b.transfer_from_nm:
                assert e.torque_nm not in b.transfer_from_nm
                assert not any(CAT.presets[p].applies_at(e.torque_nm) for p in b.presets)


def test_provenance_regressions() -> None:
    # Finding 6: GT7 realism Max. Torque is Greg G.'s own published 6 (V), and at 5 Nm it is flagged as a value
    # made for 8 Nm and stale, not presented as a verified 5 Nm value.
    real5 = recommend("gt7", Hardware(), "realism")
    mt = row(real5, "FFB_MAX_TORQUE")
    assert mt.value == "6" and mt.provenance.evidence == "V" and mt.range is None
    assert [(b.code, b.value, b.applies_at_torque) for b in mt.provenance.basis] == [("G6", "6", False)]
    assert mt.provenance.transfer and "8 Nm" in mt.provenance.transfer and mt.provenance.stale
    assert real5.stale and any("made for 8 Nm" in w for w in real5.warnings)
    real8 = row(recommend("gt7", Hardware(torque_nm=8), "realism"), "FFB_MAX_TORQUE")
    assert real8.provenance.transfer is None and real8.provenance.evidence == "V"
    # a start value inside a published range is pitwall's pick (D); the range keeps its own label
    comp8 = row(recommend("f1_25", Hardware(torque_nm=8), "competitive"), "VIB_FFB_STRENGTH")
    assert comp8.value == "95" and comp8.range == "90-100" and comp8.provenance.kind == "range_pick"
    assert comp8.provenance.evidence == "D" and comp8.provenance.range_evidence == "V"
    research, _ = docs()
    assert entry_value(research, "f1_25__8nm__competitive", "VIB_FFB_STRENGTH")["evidence"] == "V"  # research said V
    # matched against a storyboard value, a value is never better than A
    int8 = row(recommend("f1_25", Hardware(torque_nm=8), "competitive"), "INT")
    assert int8.value == "2" and int8.provenance.evidence == "A" and int8.range == "OFF-5"
    # a key the research only inferred (SimRacingSetup's 'FFS 100' read as FOR) is a derivation
    assert row(recommend("f1_25", Hardware(), "competitive", "advanced"), "FOR").provenance.derived


