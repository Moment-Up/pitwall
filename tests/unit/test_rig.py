    m = metric([lap], "brake_hold_noise", pedals="csl_load_cell")
    assert value(m) == pytest.approx(100 * 0.03 / math.sqrt(2), rel=0.1) and m.status == "warn"
    # the driver easing the brake through a hold (a straight ramp or a gentle dip) is not noise
    for brake in (lambda tt: 0.5 - 0.05 * tt, lambda tt: 0.5 - 0.04 * np.sin(np.pi * tt / 2.0)):
        smooth = synth_lap(
            [
                (6.0, STRAIGHT),
                (0.3, {"brake": ramp(0.5), "speed_kph": 250.0}),
                (2.0, {**hold, "brake": brake}),
                (6.0, STRAIGHT),
            ]
        )
        assert value(metric([smooth], "brake_hold_noise", pedals="csl_load_cell")) < 0.5


