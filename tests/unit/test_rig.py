def two_stops(gap_s: float, *, low: float = 0.0, throttle: float = 0.5) -> LapTrace:
    """Two 60% stops ``gap_s`` apart (closer than Joyce's 2 s clearance: one merged event). Between them the brake
    returns to ``low`` with the throttle at ``throttle``."""
    stop: list[tuple[float, Spec]] = [
        (0.2, {"brake": ramp(0.6, 12), "speed_kph": 250.0}),
        (0.5, {"brake": 0.6, "speed_kph": 200.0}),
        (0.3, {"brake": lambda tt: np.maximum(low, 0.6 - (np.arange(len(tt)) + 1) / 30.0), "speed_kph": 150.0}),
    ]
    between: Spec = {"throttle": throttle, "speed_kph": 150.0, "brake": low}
    return synth_lap([(6.0, STRAIGHT), *stop, (gap_s, between), *stop, (3.0, CORNER), (6.0, STRAIGHT)])


def test_merged_double_stops_are_not_reapplications() -> None:
    """Finding 5: a re-application happens within one stop; a full release or a throttle application between two
    presses makes them two stops, even when Joyce's 2 s clearance merges them into one event."""
    (released,) = brake_events(two_stops(1.5))
    assert not released.reapplied
    (load_cell,) = brake_events(two_stops(1.5, low=0.05))  # brake never reads 0, but the throttle went on
    assert not load_cell.reapplied
    (coasting,) = brake_events(two_stops(1.5, low=0.05, throttle=0.0))  # 60% -> 5% -> 60%, no throttle: same stop
    assert coasting.reapplied
    assert value(metric([two_stops(1.5, low=0.05)], "brake_reapply_count")) == 0.0


