@pytest.mark.parametrize(("game", "style", "torque", "pedals", "skill"), COMBOS)
def test_every_value_has_provenance(game: str, style: str, torque: int, pedals: str, skill: str) -> None:
    rec = recommend(game, Hardware(torque_nm=torque, pedals=pedals), style, skill)  # type: ignore[arg-type]
    rows = rec.rows()
    assert rows and {s for s, _ in rows} == {"wheel", "ingame"}
    for _section, r in rows:
        p = r.provenance
        assert r.value and p.evidence in ("V", "A", "U", "D")
        assert p.derived == (p.evidence == "D"), r
        if p.kind in ("derived", "range_pick"):
            assert p.derived and (p.derivation or p.source), r  # a derived value always says how
        elif p.kind in ("sourced", "locked"):
            assert any(ref.value == r.value for ref in p.basis) or p.original, r  # the cited preset says this
        elif p.kind == "cited":
            assert p.citations, r
        elif p.kind == "instruction":
            assert r.instruction and p.source, r
        if p.range_basis == "published":
            assert p.range_evidence in ("V", "A", "U") and r.range
        for ref in (*p.basis, *p.others):
            assert ref.id in rec.presets and ref.id != OFFICIAL_XBOX
        assert r.key not in ("MPS", "AP", "SHO", "BLI")  # finding 9: never rows for rim/pedal hardware
    assert all(step.text and step.evidence for s in rec.sections for step in s.steps)
    json.dumps(rec.to_dict())  # serialisable as-is


