def heavy_laps(peaks: list[float], *, reapply_first: bool = False) -> list[LapTrace]:
    """One heavy stop per lap with the given peaks, in session order."""
    laps = []
    for i, pk in enumerate(peaks):
        lap = synth_lap(
            [(6.0, STRAIGHT), *braking(peak=pk, dip=reapply_first and i == 0), (3.0, CORNER), (6.0, STRAIGHT)]
        )
        lap.lap_number = i + 1
        lap.channels["session_time_s"] = lap.channels["session_time_s"] + 100.0 * i
        laps.append(lap)
    return laps


