def docs() -> tuple[dict[str, Any], dict[str, Any]]:
    research: dict[str, Any] = json.loads(RESEARCH_PATH.read_text(encoding="utf-8"))
    overlay: dict[str, Any] = json.loads(OVERLAY_PATH.read_text(encoding="utf-8"))
    return research, overlay


def row(rec: Recommendation, key: str, section: str | None = None) -> SettingRow:
    r = rec.row(key, section)
    assert r is not None, f"no {key} row"
    return r


def preset_doc(research: dict[str, Any], preset_id: str) -> dict[str, Any]:
    found: dict[str, Any] = next(p for p in research["presets"] if p["id"] == preset_id)
    return found


def entry_value(research: dict[str, Any], entry_id: str, key: str) -> dict[str, Any]:
    for e in research["recommendations"]["wheel"]:
        if e["id"] == entry_id:
            v: dict[str, Any] = (e["wheel_settings"] | e["ingame_settings"])[key]
            return v
    raise KeyError(entry_id)


